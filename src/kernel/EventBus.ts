/**
 * @file /src/kernel/EventBus.ts
 * @description In-memory type-safe Event Bus implementing IEventBus.
 * Features wildcard routing, chronological Event Journaling, and replay capability.
 */

import { EventEmitter } from "events";
import { IEventBus, KernelEvent, KernelEventType } from "./types";
import { getRequestId } from "./context";

/**
 * Robust in-memory Event Bus routing event envelopes to subscribers.
 * Keeps an append-only transaction journal for compliance, audits, and state replays.
 */
export class InMemoryEventBus implements IEventBus {
  private readonly emitter = new EventEmitter();
  private readonly journal: KernelEvent[] = [];

  constructor() {
    // Avoid memory leak warnings during extensive high-volume stress testing
    this.emitter.setMaxListeners(0);
  }

  /**
   * Generates a safe, unique ID for trace and compliance.
   */
  private generateId(): string {
    const randomHex = (): string => Math.floor((1 + Math.random()) * 0x10000).toString(16).substring(1);
    return `ev_${randomHex()}${randomHex()}-${randomHex()}-${randomHex()}-${randomHex()}-${randomHex()}${randomHex()}${randomHex()}`;
  }

  /**
   * Dispatches a type-safe event frame out to all matched listeners.
   * Automatically appends a unique event ID and current RFC 3339 timestamp.
   * @param event Frame input parameters excluding autogenerated fields
   */
  public publish(event: Omit<KernelEvent, "eventId" | "timestamp">): void {
    const fullEvent: KernelEvent = {
      ...event,
      eventId: this.generateId(),
      timestamp: new Date().toISOString(),
      requestId: getRequestId()
    };

    // Deep-clone and record to compliance audit journal to isolate memory references
    this.journal.push(JSON.parse(JSON.stringify(fullEvent)));

    // Publish to specific event-type channel
    this.emitter.emit(fullEvent.type, fullEvent);

    // Publish to wildcard channel
    this.emitter.emit("*", fullEvent);
  }

  /**
   * Subscribes a listener to trigger when a matching event occurs.
   * Wildcard "*" channel matches every dispatched event.
   * @param type Targeted event type or "*" wildcard
   * @param handler Unhandled-safe callback handler
   * @returns Unsubscribe closure function to simplify consumer cleanup lifecycle
   */
  public subscribe(type: KernelEventType | "*", handler: (event: KernelEvent) => void): () => void {
    const wrapper = (event: KernelEvent) => {
      try {
        handler(event);
      } catch (err) {
        console.error(`[EventBus] Subscriber thrown uncaught exception for channel "${type}":`, err);
      }
    };

    this.emitter.on(type, wrapper);

    // Return unsubscribe cleanup handler
    return () => {
      this.emitter.off(type, wrapper);
    };
  }

  /**
   * Unsubscribes a listener directly using explicit channel.
   * @param type Channel name or wildcard
   * @param handler Listener callback reference
   */
  public unsubscribe(type: KernelEventType | "*", handler: (event: KernelEvent) => void): void {
    this.emitter.off(type, handler);
  }

  /**
   * Retrieves complete chronological event audit ledger.
   */
  public getJournal(): KernelEvent[] {
    return JSON.parse(JSON.stringify(this.journal));
  }

  /**
   * Replays chronological journal records to a target listener.
   * Useful for auditing, testing, and debugging state reconstruction.
   * @param handler Target listener to feed events to
   * @param filters Optional filtering parameters to scope replay volume
   */
  public replay(
    handler: (event: KernelEvent) => void,
    filters?: { type?: string; taskId?: string }
  ): void {
    for (const event of this.journal) {
      if (filters?.type && event.type !== filters.type) continue;
      if (filters?.taskId && event.taskId !== filters.taskId) continue;

      try {
        handler(JSON.parse(JSON.stringify(event)));
      } catch (err) {
        console.error(`[EventBus] Error occurred during chronological event replay:`, err);
      }
    }
  }

  /**
   * Purges active event listener registry and journals to prevent leakages.
   */
  public clear(): void {
    this.journal.length = 0;
    this.emitter.removeAllListeners();
  }
}
